//! # 三条不变式（后续 T2–T7 都必须遵守）
//!
//! 1. **可见性只有一处实现**：任何"列出任务"的查询都必须经由
//!    [`model::page_visible`] / [`model::find_detail`] / [`model::list_children`]，
//!    它们共用一条谓词 [`model::VISIBLE_OR_TAIL`]（`数据范围 ∪ 参与 id 数组`，
//!    数组由 [`model::my_member_task_ids`] 解析：负责人 ∪ 创建人 ∪ 分派人 ∪ 协作人）。
//!    另写一条 `WHERE owner_id = ?` 当"可见性"用，就会退化成"看不到别人分给我的任务"；
//!    往谓词里再加 `OR` 分支则会让索引失效（决策 D6，见 [`model`] 模块文档的实测对比）。
//! 2. **不改 `business/shared/scope.rs`**：它是批次 B 的门禁核心（闸①/闸② 与启动自检
//!    都盯着它）。任务表的可见性是 OR 语义，本模块用**本地锚点** [`model::TASK_TARGET`]
//!    + `(1 = 1 {FILTER})` 拼法实现，`scope.rs` 一行没动。
//! 3. **写权限 ≠ 可见性**：协作人看得见但改不了；编辑只认「负责人 / 创建人」，
//!    删除额外认「超管」。每次都要 `find_raw` 现查，不信前端传来的角色。
//!
//! # 与其它模块的边界
//!
//! - **变更日志**：T1 不写 `sys_change_log`；**T2 已登记 `biz_task`**
//!   （`changelog/diff.rs` 的 `REGISTRY`）并只记状态流转（`action = STATUS`）——
//!   白名单字段：`status` / `progress` / `done_at` / `reject_reason` / `cancel_reason`。
//!   编辑类字段（标题 / 优先级）的留痕留待 T6 详情页定稿；
//!   **T3 已把 `owner_id` / `assigner_id` / `source` 加进白名单**（转派要记「原来是谁」）。
//! - **通知**：走 `business::notice::dispatch`，按修正 8 分级；**通知失败不回滚业务**。
//!   分级只有一处实现（`notice` 的扇出 SQL），本模块只负责传 `force`：
//!
//!   | 事件 | 收件人 | `force` |
//!   |------|--------|---------|
//!   | 被分派 / 被转派 | 新负责人 / 原负责人 | `true`（强制） |
//!   | 被加为协作人 | 被加的人 | `true`（强制） |
//!   | 协作人被移除 | 被移除的人 | `false`（尊重偏好） |
//!   | 被打回 / 待你验收 | 负责人 / 创建人 + 分派人 | `true`（强制） |
//!   | 其它状态变更 / 子任务全部完成 | 负责人 + 创建人 | `false`（尊重偏好） |
//!
//! - **AI 执行者（修正 11）**：分派 / 协作人**只查权限码**，不硬拒 `user_type`
//!   （所以「授予 AI 团队主管角色后能分派」自然成立）；删任务则**硬拒 ROBOT**。
//! - **附件**：`biz_task_attachment` 只落绑定关系，文件本体由 `business::storage` 管
//!   （T1 建表，接口随 T3 的评论/附件一起做）。
//! - **审批流**：`biz_task.approval_instance_id` 本批恒为 NULL（批次 D 预留）。
//!
//! # T4 落地的两条不变式（依赖 + 甘特）
//!
//! 1. **环检测只有一份实现**：[`dep::find_cycle`]（纯逻辑，内存 BFS，带 100 层深度上限）
//!    在**事务内**基于全量 FS 边判定，写入前用 `pg_advisory_xact_lock` 串行化
//!    （见 [`handler::add_dependency`]）。**不要**在别处再写一次「顺着依赖走一圈」
//!    的判断 —— 两份实现的第一次分歧就会漏掉一个环。
//! 2. **甘特只读**：`GET /business/task/gantt` 只出数据（含后端算好的
//!    `bar.offset_days` / `length_days`），前端**不绑拖拽**。拖拽改期属 T7，
//!    且必须重跑依赖校验（修正 10：改期后前置不得晚于后继开始）。

