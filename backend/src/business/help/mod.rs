//! 依据 `docs/批次C-技术架构.md` §3（帮助文档）：分类树 + 文档 + 版本快照的表设计（§3.1）、
//! Markdown 站内渲染与 TOC 生成（§3.2）、检索方案结论（§3.3，`ILIKE` + 转义）、
//! 权限（§3.4）、与公告的边界（§3.5）、API 契约（§3.6）。
//!
//! # 文件分工
//!
//! | 文件 | 职责 |
//! |------|------|
//! | [`model`] | 三张表的数据访问 + 领域规则（深度 ≤ 3 / 分类非空 / 版本号只增不减 / 检索转义 / 片段生成） |
//! | [`dto`] | 请求与响应结构（时间 RFC3339、ID 一律 `String`、可空列降级为空串） |
//! | [`handler`] | 15 个接口的路由、权限分流、闸 3 净化、阅读量去重 |
//!
//! # 五条不变量（C4 与后续维护者都必须遵守）
//!
//! 1. **渲染与净化统一走** [`crate::business::shared::content`]，且**必须**用
//!    `Recipe::Help`：只有这一套配方会保留 heading 的锚点 `id`（`h-{level}-{index}`），
//!    TOC 跳转依赖它；任何"自己拼 HTML"的写法都是红线；
//! 2. **TOC 不落库**：直接取 `content::Rendered::toc`（架构 §3.2 已否决"单独存 `toc`
//!    JSONB 列"：内容变更要同步维护，容易不一致）；
//! 3. **检索方案不变**：`ILIKE` + 转义 + 状态过滤（架构 §3.3 的实测结论：`tsvector`
//!    在无中文分词器的 PG 上搜「公告」命中 0；`pg_trgm` 对 2 字中文反而更慢）。
//!    trgm 升级预案是**注释态**，写在 `V0083` 里，等文档数 > 5000 再放开；
//! 4. **版本号只增不减**：保存 / 发布 / 回滚都 `version + 1` 并写快照；回滚是"用旧内容
//!    生成新版本"，历史一行不删（H-06）；
//! 5. **分类树深度 ≤ 3 由 model 层用递归 CTE 保证**：数据库无法用 CHECK 表达"深度"，
//!    所以创建与移动两条路径都必须调 `category_depth` / `subtree_height`（H-01）。
//!
//! # 与公告的边界（架构 §3.5）
//!
//! 两张独立主表，共用 `business/shared/content` 的渲染与净化能力；帮助文档
//! **不触发任何通知扇出**（改一条 FAQ 就给全员发通知是事故），也**不支持附件**
//! （Markdown 图片指向 `business/storage` 即可）。
//!
