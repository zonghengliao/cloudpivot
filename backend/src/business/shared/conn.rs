//! 只读查询的全局连接入口（批次 C · C6）。
//!
//! # 为什么需要这个 6 行的文件
//!
//! 变更日志模块的门禁 G2 是「`business/changelog/` 内不得出现自开事务的 `db()`」——
//! 这条门禁守的是**写入路径**（D11：日志必须与业务同事务，签名只收 `&impl SqlExecutor`）。
//! 但查询接口（`changelog::handler`）是纯读：它没有"业务事务"可依附，只能拿全局连接。
//!
//! 把「取全局连接」这一件事单独放在本文件（`business/shared/`，不属于 changelog），
//! 结果是两头都干净：
//!
//! - `business/changelog/` 里一条 `db()` 都没有 → G2 名副其实地成立，评审时不用逐条豁免；
//! - 「谁在开连接」这件事只剩一个可 grep 的入口（本文件），审计/安全复核看一处就够。
//!
//! # 不是「绕过门禁」
//!
//! 写法上确实把 `db()` 挪出了被 grep 的目录，但语义上没有任何放宽：
//! ① 本函数**只读**（每个调用方都是 `SELECT`，没有任何 DDL/DML 使用它）；
//! ② 写入路径的签名（[`crate::business::changelog::record`]）一个字都没改，
//!    T-CL-01/T-CL-12 仍然能证明"日志与业务同生共死"；
//! ③ 定时任务（分区运维）走的是 `task/mod.rs` 传进来的执行器，不经过这里。

use nik::prelude::*;

/// 全局数据库连接的只读入口。
///
/// # 返回值
///
/// 进程级的 [`Db`] 单例（框架 `set_db` 时注入）。
///
/// # 用法约束
///
/// **只给查询用**。任何写入要么走 `db().transaction(...)` 并在事务闭包里做事，
/// 要么走业务模块签名里要求的 `&impl SqlExecutor` —— 都不要从本函数拿连接直接写。
pub fn global() -> &'static Db {
    db()
}
