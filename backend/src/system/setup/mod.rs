//! 首次启动向导（FIX-1 · 新环境开箱即用）。
//!
//! # 它解决的两个「新环境第一小时」问题
//!
//! ```text
//! ① 空库只有 admin：任何审批单一提交就 422 / 65018（内控不许自审）
//!    → 本模块给前端一份「哪些关键角色没人」的清单 + 一键指派 / 一键建演示账号
//!
//! ② 开发 / 测试环境想直接跑六条链：不想手工建 9 个账号
//!    → NIK_SEED_DEMO_USERS=true 启动即建（幂等，已有账号不重复建）
//! ```
//!
//! # 文件
//!
//! | 文件 | 内容 |
//! |------|------|
//! | [`model`] | 关键角色 / 演示账号清单、成员数查询、批量加人、演示账号种子 |
//! | [`dto`] | 三个接口的出入参 |
//! | [`handler`] | 自检 / 指派 / 建演示账号 |
//!
//! # 接口一览
//!
//! | 方法 | 路径 | 权限码 | 说明 |
//! |------|------|--------|------|
//! | GET | `/system/setup/check` | `system:setup:read` | 关键角色谁还没人 |
//! | POST | `/system/setup/assign` | `system:setup:manage` | 批量指派角色成员（只增不减） |
//! | POST | `/system/setup/demo-users` | `system:setup:manage` | 一键创建演示账号 |
//!
//! # 与 `business::flow::no_assignee` 的分工
//!
//! - `no_assignee`：**失败后**解释「为什么没人」（错误体载荷，前端弹引导框）；
//! - 本模块：**事前 + 事后**的修复动作（向导清单、指派接口）。
//!
//! 前端把两者接在一起：`65018` 载荷里的 `role_code` 直接喂给 `/system/setup/assign`，
//! 指派成功后自动重试刚才那次提交。

