//! 用户偏好体系（通用 KV + 字典元数据）。
//!
//! # 一句话
//!
//! 「用户的界面观感偏好」不再只存在浏览器里 —— 配色方案、明暗模式、侧边栏折叠、
//! 表格密度、默认分页、界面语言、两个通知开关，全部按 **`user_id` + `pref_key`** 落库，
//! 换浏览器 / 清 localStorage 之后重新登录仍是同一套外观。
//!
//! # 为什么是「KV 主表 + 字典表」而不是「一行三列」
//!
//! 一行三列（`palette` / `theme_mode` / `side_compact`）每加一个偏好就要改表结构 + 改
//! 后端 + 发版，而且没法回答「合法取值有哪些」「默认值是什么」。
//! 两级结构把**值与元数据分开**：
//!
//! | 表 | 职责 | 加偏好要做什么 |
//! |----|------|----------------|
//! | `sys_preference_def` | 键名 / 中文名 / 类型 / 默认值 / 分组 / 校验规则 | **插一行** |
//! | `sys_user_preference` | 用户显式设置过的值（`jsonb`） | 什么都不用做 |
//!
//! # 模块结构
//!
//! | 文件 | 职责 |
//! |------|------|
//! | [`dto`] | 请求（两代形态）/ 响应（兼容字段 + 全量 `items`） |
//! | [`model`] | 字典与用户值的读写 + **唯一**的校验/合并实现（纯函数带单测） |
//! | [`handler`] | GET / PUT 两个接口（`/system/auth/preference`） |
//!
//! # 接口
//!
//! | 方法 | 路径 | 说明 |
//! |------|------|------|
//! | GET | `/api/system/auth/preference` | 合并默认值的全量偏好，无记录也返默认 |
//! | PUT | `/api/system/auth/preference` | 局部更新 + upsert，逐 key 按字典校验 |
//!
//! 迁移：`V0090`（两张表）+ `V0091`（8 项预置字典）。
//!
//! # 数据权限
//!
//! 偏好没有「部门归属」概念，不登记 `shared/scope.rs` 的 `SCOPED_TABLES`；行级隔离就是
//! `user_id = AuthClaims.sub`（见 [`model`] 的 SCOPE-EXEMPT 说明）。

pub mod dto;
