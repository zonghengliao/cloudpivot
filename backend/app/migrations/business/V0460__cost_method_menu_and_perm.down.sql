-- ============================================================================
-- V0460 回滚：成本方法配置 · 菜单 / 权限点 / 授权
--
--   顺序：① 删本迁移授的授权行（按 4 个 menu_id 精确删，不按 role 通配）
--         ② 删 3 个按钮 → ③ 删页面行
--   护栏：页面下若出现本迁移之外的子菜单 → 拒绝（有人挂过东西，别替人删）。
--   幂等：DELETE 按 id，重跑 0 行。
-- ============================================================================

DO $$
DECLARE
    v_extra integer;
BEGIN
    -- ① 授权行
    DELETE FROM sys_role_menu
     WHERE menu_id IN ('20000000-0000-4000-8000-00000000d101'::uuid,
                       '20000000-0000-4000-8000-00000000d111'::uuid,
                       '20000000-0000-4000-8000-00000000d112'::uuid,
                       '20000000-0000-4000-8000-00000000d113'::uuid);

    -- ② 护栏：页面下不许有本迁移之外的子菜单
    SELECT count(*) INTO v_extra
      FROM sys_menu
     WHERE deleted_at IS NULL
       AND parent_id = '20000000-0000-4000-8000-00000000d101'::uuid
       AND id NOT IN ('20000000-0000-4000-8000-00000000d111'::uuid,
                      '20000000-0000-4000-8000-00000000d112'::uuid,
                      '20000000-0000-4000-8000-00000000d113'::uuid);
    IF v_extra > 0 THEN
        RAISE EXCEPTION 'V0460 拒绝回滚：成本方法页面下还有 % 条本迁移之外的子菜单（请先人工确认）', v_extra;
    END IF;

    -- ③ 按钮 → 页面
    DELETE FROM sys_menu
     WHERE id IN ('20000000-0000-4000-8000-00000000d111'::uuid,
                  '20000000-0000-4000-8000-00000000d112'::uuid,
                  '20000000-0000-4000-8000-00000000d113'::uuid);
    DELETE FROM sys_menu WHERE id = '20000000-0000-4000-8000-00000000d101'::uuid;

    RAISE NOTICE 'V0460 回滚完成：成本方法菜单（1 页面 + 3 按钮）与授权已删除';
END $$;
