-- ============================================================================
-- V0456 回滚：框架协议维护链路（M4-11b）
--
--   **有协议单就拒绝回滚**：本迁移删的是「维护入口」（权限码 / 审批流程），
--   库里已有的协议行本身不受影响；但一旦把这些入口撤掉，已提交 / 审批中的协议
--   就再也没有任何人能推进它（没有待办、没有接口）—— 所以只在**一张协议都没有**时允许回滚。
--   真要停用功能请 `UPDATE sys_menu SET status = 0`，而不是回滚迁移。
--
--   顺序：流程四层（审批人 → 边 → 节点 → 版本 → 定义）→ 授权 → 菜单。
-- ============================================================================

DO $$
DECLARE
    n_rows INT;
BEGIN
    SELECT count(*) INTO n_rows FROM biz_framework_agreement;
    IF n_rows > 0 THEN
        RAISE EXCEPTION 'V0456 回滚被拒：biz_framework_agreement 里还有 % 份协议（回滚会撤掉维护入口，让它们没人能推进）', n_rows;
    END IF;
END $$;

-- ① 流程四层（先子后父）
DELETE FROM biz_flow_node_assignee
 WHERE node_id IN ('20000000-0000-4000-8000-0000000d06a4'::uuid,
                   '20000000-0000-4000-8000-0000000d06a5'::uuid);
DELETE FROM biz_flow_edge WHERE version_id = '20000000-0000-4000-8000-0000000d06a2'::uuid;
DELETE FROM biz_flow_node WHERE version_id = '20000000-0000-4000-8000-0000000d06a2'::uuid;
DELETE FROM biz_flow_def_version WHERE id = '20000000-0000-4000-8000-0000000d06a2'::uuid;
DELETE FROM biz_flow_def WHERE id = '20000000-0000-4000-8000-0000000d06a1'::uuid;

-- ② 授权
DELETE FROM sys_role_menu
 WHERE menu_id IN ('20000000-0000-0000-0000-000000004490'::uuid,
                   '20000000-0000-0000-0000-000000004491'::uuid,
                   '20000000-0000-0000-0000-000000004492'::uuid,
                   '20000000-0000-0000-0000-000000004493'::uuid,
                   '20000000-0000-0000-0000-000000004494'::uuid);

-- ③ 菜单（页面行 …004480 与执行量行 …004481 属 V0452，**不动**）
