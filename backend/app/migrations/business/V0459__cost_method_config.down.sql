-- ============================================================================
-- V0459 回滚：成本方法配置表
--
--   **有数据就拒绝回滚**：配置行是「某段期间按哪种方法算成本」的口径凭据
--   （M5-31 切换策略、事后复盘都按它查），删掉之后没人能解释历史期间怎么算的。
--   真要在生产上撤这块功能，正确做法是先把配置导出存档
--   （`COPY biz_cost_method_config TO …`），再手工把 deleted_at 之外的行走软删，
--   而不是让迁移脚本替人删证据。
--
--   判定口径：**除默认种子行（…d001）之外的任何存活行**都算「有数据」。
--   库里只有种子行 = 还没人配过 = 回滚安全（种子行由本迁移建，一起删掉）。
--
--   幂等：DROP TABLE IF EXISTS，重跑无副作用。
-- ============================================================================

DO $$
DECLARE
    v_rows integer;
BEGIN
    SELECT count(*) INTO v_rows
      FROM biz_cost_method_config
     WHERE deleted_at IS NULL
       AND id <> '20000000-0000-4000-8000-00000000d001'::uuid;

    IF v_rows > 0 THEN
        RAISE EXCEPTION 'V0459 拒绝回滚：表里还有 % 条存活配置（除默认种子外）。'
                        '配置是期间口径的凭据，请先导出存档 / 软删，再回滚本迁移', v_rows;
    END IF;
END $$;

DROP TABLE IF EXISTS biz_cost_method_config;
