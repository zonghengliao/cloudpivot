-- ======================================================
-- V0229 down：先把「功能已被使用」的情况挡住，再删表
--
-- 与 V0228 同口径：**有业务数据就拒绝回滚**。
-- 理由：`biz_fixed_asset_change` 对 `biz_fixed_asset` 是 RESTRICT 外键，
-- 直接 DROP 会在有卡片时抛 fkey 错误（可读性极差，且没人知道该先删什么）。
-- 自己先数、先 RAISE，报错信息才能指路。
-- ======================================================
DO $$
DECLARE
    n int;
BEGIN
    -- 只在表还在的时候数（down 是按逆序执行的：V0230 已经把折旧表删掉了，
    -- 这里再去查 biz_depreciation_batch 只会得到「关系不存在」的假失败）
    IF to_regclass('public.biz_fixed_asset') IS NOT NULL THEN
        SELECT count(*) INTO n FROM biz_fixed_asset;
        IF n > 0 THEN
            RAISE EXCEPTION 'V0229 回滚被拒绝：库里还有 % 张固定资产卡片（含软删），请先确认这些卡与它们的购入凭证如何处理', n;
        END IF;
    END IF;
    IF to_regclass('public.biz_depreciation_batch') IS NOT NULL THEN
        SELECT count(*) INTO n FROM biz_depreciation_batch;
        IF n > 0 THEN
            RAISE EXCEPTION 'V0229 回滚被拒绝：库里还有 % 条折旧批次（折旧表由 V0230 建，回滚顺序应从 V0230 开始）', n;
        END IF;
    END IF;
END $$;

