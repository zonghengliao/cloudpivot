-- ======================================================
-- V0308 回滚：价格维护页的菜单 / 按钮 / 授权
--
-- 顺序（不能反）：
--   ① 先删 `sys_role_menu` 授权行（父页与按钮、以及本迁移补的取价码授权）；
--   ② 再删 7 个按钮（menu_type=3）；
--   ③ 最后删页面节点。
-- 反过来的话，`sys_role_menu.menu_id` 外键会把菜单行变成「删不掉」的孤儿。
--
-- 注意：本迁移补授的 `business:erp:price:resolve`（V0307 …3071）**一并撤回**，
-- 因为它是随本次授权一起进来的；V0307 的菜单行本身不动（那是 SO-33 的资产）。
-- 幂等：全部按固定 uuid 删除，重复执行 no-op。
-- ======================================================

-- ① 授权：页面 + 7 个按钮 + 取价码
DELETE FROM sys_role_menu
 WHERE menu_id IN (
        '20000000-0000-0000-0000-000000003081'::uuid,
        '20000000-0000-0000-0000-000000003082'::uuid,
        '20000000-0000-0000-0000-000000003083'::uuid,
        '20000000-0000-0000-0000-000000003084'::uuid,
        '20000000-0000-0000-0000-000000003085'::uuid,
        '20000000-0000-0000-0000-000000003086'::uuid,
        '20000000-0000-0000-0000-000000003087'::uuid,
        '20000000-0000-0000-0000-000000003088'::uuid,
        '20000000-0000-0000-0000-000000003071'::uuid
    );

-- ② 按钮（3082–3088）
DELETE FROM sys_menu
 WHERE id BETWEEN '20000000-0000-0000-0000-000000003082'::uuid
              AND '20000000-0000-0000-0000-000000003088'::uuid
   AND menu_type = 3;

-- ③ 页面节点
DELETE FROM sys_menu
 WHERE id = '20000000-0000-0000-0000-000000003081'::uuid;
