-- ======================================================
-- V0288 回滚：应收单接口的 5 个权限码（SO-13）
--
-- 顺序：先删授权行（`sys_role_menu`），再删按钮（menu_type=3），最后删页面节点。
-- 反过来删会留下指向不存在菜单的授权行（`orphan_button_gate` 会报孤儿）。
-- ======================================================

DELETE FROM sys_role_menu
 WHERE menu_id IN (
     '20000000-0000-0000-0000-000000002880'::uuid,
     '20000000-0000-0000-0000-000000002881'::uuid,
     '20000000-0000-0000-0000-000000002882'::uuid,
     '20000000-0000-0000-0000-000000002883'::uuid,
     '20000000-0000-0000-0000-000000002884'::uuid
 );

DELETE FROM sys_menu
 WHERE id IN (
     '20000000-0000-0000-0000-000000002881'::uuid,
     '20000000-0000-0000-0000-000000002882'::uuid,
     '20000000-0000-0000-0000-000000002883'::uuid,
     '20000000-0000-0000-0000-000000002884'::uuid
 );

DELETE FROM sys_menu
 WHERE id = '20000000-0000-0000-0000-000000002880'::uuid;
