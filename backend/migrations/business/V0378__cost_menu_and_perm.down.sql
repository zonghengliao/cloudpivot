-- ============================================================================
-- V0378.down.sql —— 回滚成本核算的菜单 / 按钮权限 / 角色授权（对应 V0378__cost_menu_and_perm）
--
-- 顺序：授权 → 按钮（menu_type=3）→ 页面（menu_type=2）
--       （sys_role_menu.menu_id 有外键指向 sys_menu，先删引用侧）
--
-- 两道护栏（宁可 down 失败也不留裂树）：
--   ① 6 个页面下如果挂出了**本迁移之外**的子菜单（有人在其下加了自定义页面/按钮）→ 拒绝；
--   ② 20 个按钮下如果挂了任何子节点 → 拒绝（按钮不该有子节点，说明数据被人手工改坏）。
--
-- 不动的东西：sys_role / biz_* 业务表 / 其它迁移种的菜单。授权只按**本迁移的 26 个 menu_id** 删，
-- 不做 (role_code, auth_code) 通配 —— 那样会误伤同码的其它菜单授权。
-- ============================================================================

DO $$
DECLARE
    own_pages UUID[] := ARRAY[
        '20000000-0000-4000-8000-00000000c001','20000000-0000-4000-8000-00000000c002',
        '20000000-0000-4000-8000-00000000c003','20000000-0000-4000-8000-00000000c004',
        '20000000-0000-4000-8000-00000000c005','20000000-0000-4000-8000-00000000c006'
    ]::uuid[];
    own_btns UUID[] := ARRAY[
        '20000000-0000-4000-8000-00000000c101','20000000-0000-4000-8000-00000000c102',
        '20000000-0000-4000-8000-00000000c103','20000000-0000-4000-8000-00000000c104',
        '20000000-0000-4000-8000-00000000c111','20000000-0000-4000-8000-00000000c112',
        '20000000-0000-4000-8000-00000000c113','20000000-0000-4000-8000-00000000c114',
        '20000000-0000-4000-8000-00000000c121','20000000-0000-4000-8000-00000000c122',
        '20000000-0000-4000-8000-00000000c131','20000000-0000-4000-8000-00000000c132',
        '20000000-0000-4000-8000-00000000c133','20000000-0000-4000-8000-00000000c134',
        '20000000-0000-4000-8000-00000000c141','20000000-0000-4000-8000-00000000c142',
        '20000000-0000-4000-8000-00000000c143','20000000-0000-4000-8000-00000000c144',
        '20000000-0000-4000-8000-00000000c151','20000000-0000-4000-8000-00000000c152'
    ]::uuid[];
    n_extra_page INT;
    n_extra_btn  INT;
    sample       TEXT;
    n_grant      INT;
    n_del        INT;
BEGIN
    -- ① 页面下不许有本迁移之外的子菜单
    SELECT count(*), string_agg(c.path || ' (' || c.id::text || ')', '; ')
      INTO n_extra_page, sample
      FROM sys_menu c
     WHERE c.parent_id = ANY(own_pages) AND NOT (c.id = ANY(own_btns));
    IF n_extra_page > 0 THEN
        RAISE EXCEPTION 'V0378.down 拒绝执行：成本页面下存在 % 个本迁移之外的子菜单（%）—— 请先人工处理',
            n_extra_page, sample;
    END IF;

    -- ② 按钮下不许有子节点
    SELECT count(*), string_agg(c.path || ' (' || c.id::text || ')', '; ')
      INTO n_extra_btn, sample
      FROM sys_menu c
     WHERE c.parent_id = ANY(own_btns);
    IF n_extra_btn > 0 THEN
        RAISE EXCEPTION 'V0378.down 拒绝执行：成本按钮下存在 % 个子节点（%）—— 数据被手工改坏，请先人工处理',
            n_extra_btn, sample;
    END IF;

    -- ③ 删授权（按本迁移的 26 个 menu_id）
    DELETE FROM sys_role_menu WHERE menu_id = ANY(own_pages || own_btns);
    GET DIAGNOSTICS n_grant = ROW_COUNT;

    -- ④ 删按钮，再删页面
    DELETE FROM sys_menu WHERE id = ANY(own_btns);
    DELETE FROM sys_menu WHERE id = ANY(own_pages);
    GET DIAGNOSTICS n_del = ROW_COUNT;

    RAISE NOTICE 'V0378.down：已删除 % 条授权、% 条菜单（按钮+页面共 26）', n_grant, n_del;
END $$;
