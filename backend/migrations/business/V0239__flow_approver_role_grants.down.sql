-- V0239__flow_approver_role_grants.down.sql
--
-- 回滚「审批角色实例侧权限授权」。
--
-- ⚠ 授权行（sys_role_menu）没有"来源"列，无法区分"本文件加的"与"人手工勾的"。
--   本 down 按**菜单节点**清理：删掉这 8 个节点上的全部授权。若升级前有人工勾选
--   （演示库现场修补就是这么来的），回滚会一并删掉 —— 回滚只用于开发/演练环境。
--   生产回滚前先导出：
--     SELECT role_id, menu_id FROM sys_role_menu
--      WHERE menu_id IN ('20000000-0000-0000-0000-000000000800',
--                        '20000000-0000-0000-0000-000000000801',
--                        '20000000-0000-0000-0000-000000000802',
--                        '20000000-0000-0000-0000-000000000803',
--                        '20000000-0000-0000-0000-000000000804',
--                        '20000000-0000-0000-0000-000000000860',
--                        '20000000-0000-0000-0000-000000000861',
--                        '20000000-0000-0000-0000-000000000862');
--
-- 不动：权限点（sys_menu 行）本身，也不动 business:flow:read/create/update/delete/publish
--       （…0780–…0785，归 V0121/V0124/S__workflow_permissions 管）。
-- ============================================================================

DELETE FROM sys_role_menu
 WHERE menu_id IN ('20000000-0000-0000-0000-000000000800'::uuid,
                   '20000000-0000-0000-0000-000000000801'::uuid,
                   '20000000-0000-0000-0000-000000000802'::uuid,
                   '20000000-0000-0000-0000-000000000803'::uuid,
                   '20000000-0000-0000-0000-000000000804'::uuid,
                   '20000000-0000-0000-0000-000000000860'::uuid,
                   '20000000-0000-0000-0000-000000000861'::uuid,
                   '20000000-0000-0000-0000-000000000862'::uuid);

-- 自检：8 个节点上必须零授权（其他节点的授权不动，不做总数断言）
DO $$
DECLARE
    left_rows int;
BEGIN
    SELECT count(*) INTO left_rows
      FROM sys_role_menu
     WHERE menu_id IN ('20000000-0000-0000-0000-000000000800'::uuid,
                       '20000000-0000-0000-0000-000000000801'::uuid,
                       '20000000-0000-0000-0000-000000000802'::uuid,
                       '20000000-0000-0000-0000-000000000803'::uuid,
                       '20000000-0000-0000-0000-000000000804'::uuid,
                       '20000000-0000-0000-0000-000000000860'::uuid,
                       '20000000-0000-0000-0000-000000000861'::uuid,
                       '20000000-0000-0000-0000-000000000862'::uuid);
    IF left_rows <> 0 THEN
        RAISE EXCEPTION 'V0239 down 自检失败：8 个实例侧节点上仍残留 % 行授权', left_rows;
    END IF;

    RAISE NOTICE 'V0239 down 自检通过：8 个实例侧节点授权已清空';
END
$$;
