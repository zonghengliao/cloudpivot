-- ======================================================
-- V0107 回滚：删掉任务管理的两条存储策略
--
-- 只删本迁移插入的行（固定 id + category 双限定）：
--   · category = 'task'    → id 24000000-0000-4000-8000-000000000007
--   · category = 'task_ai' → id 24000000-0000-4000-8000-000000000008
--
-- 提醒（与 V0048 / V0086 同款）：
--   1. `sys_file.category` 是**值引用、无外键**。删掉策略行不会让已上传的历史文件
--      失效 —— 读路径（签名 URL / 下载）不看策略表；只有**新的上传**会受影响。
--   2. 删掉后若业务再用 `category=task` 上传，handler 会走两级回退
--      （`document` → 内置默认策略 50 MB / 不限制扩展名）—— 注意内置默认策略
--      **不限制扩展名**，等于把「硬禁止」的外层白名单拿掉了；运行层的黑名单
--      （`FORBIDDEN_EXECUTABLE_EXTENSIONS`）仍然拦可执行，但这已不是原设计意图。
--      ⇒ 回滚仅用于「迁移写错了要重来」，不要在生产上长期停在回滚态。
--   3. 限定了 id：运维若自己建过同名 category 的行（软删后重建会拿到新 id），这里
--      不会误删它。
-- ======================================================

DELETE FROM sys_storage_policy
 WHERE category = 'task'
   AND id = '24000000-0000-4000-8000-000000000007'::uuid;

DELETE FROM sys_storage_policy
 WHERE category = 'task_ai'
   AND id = '24000000-0000-4000-8000-000000000008'::uuid;
