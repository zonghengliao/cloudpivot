-- ======================================================
-- V0132 回滚：删除示范项目与示范任务（零残留）
--
-- 顺序：示范任务 → 摘掉别人挂在这两个项目下的任务（project_id 置 NULL）
--       → 项目。`biz_task.project_id` 是 FK 且**没有 ON DELETE CASCADE**，
-- 直接删项目会被外键拦住 —— 这里不删别人的任务，只把关联摘掉
-- （任务本身属于用户数据，删项目不应该连带删任务，与 project/down 的语义一致）。
-- ======================================================

-- ---------- 1) 示范任务（按固定 id + 编号双保险） ----------
DELETE FROM biz_task
 WHERE id IN (
        '27500000-0000-4000-8000-000000000001'::uuid,
        '27500000-0000-4000-8000-000000000002'::uuid,
        '27500000-0000-4000-8000-000000000003'::uuid,
        '27500000-0000-4000-8000-000000000004'::uuid,
        '27500000-0000-4000-8000-000000000005'::uuid,
        '27500000-0000-4000-8000-000000000006'::uuid
   )
    OR task_no IN (
        'TSK-202610-000201', 'TSK-202610-000202', 'TSK-202610-000203',
        'TSK-202610-000204', 'TSK-202610-000205', 'TSK-202610-000206'
   );

-- ---------- 2) 摘掉仍挂在这两个项目下的任务（用户自己建的任务） ----------
UPDATE biz_task
   SET project_id = NULL,
       updated_at = now()
 WHERE project_id IN ('27000000-0000-4000-8000-000000000001'::uuid,
                      '27000000-0000-4000-8000-000000000002'::uuid);

-- ---------- 3) 项目成员（V0115 的 biz_project_member 是 ON DELETE CASCADE，
--              这里显式删便于 down 后可读地核对「零残留」） ----------
DELETE FROM biz_project_member
 WHERE project_id IN ('27000000-0000-4000-8000-000000000001'::uuid,
                      '27000000-0000-4000-8000-000000000002'::uuid);

-- ---------- 4) 项目 ----------
DELETE FROM biz_project
 WHERE id IN ('27000000-0000-4000-8000-000000000001'::uuid,
              '27000000-0000-4000-8000-000000000002'::uuid)
    OR project_no IN ('CP-ITER', 'DEMO-EC');
