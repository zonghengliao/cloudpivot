-- V0084 回滚：删除 `sys_change_log`（含全部分区）
--
-- 数据影响：变更日志历史（字段级审计凭证）**不可恢复**。分区是父表的子表，
-- `DROP TABLE` 会连带删除全部 `sys_change_log_YYYY_MM`，无需逐个 DROP。
--
-- 顺序约束：先回滚 C5/C6 的代码（`business/changelog` 的写入与查询），再回滚本迁移——
-- 否则仍在运行的代码会在下一次写入时报 `relation "sys_change_log" does not exist`（500），
-- 而 `record()` 与业务同事务，会连带把业务事务一起打回滚（这是 D11 的必然结果）。
-- ======================================================

DROP TABLE IF EXISTS sys_change_log;
