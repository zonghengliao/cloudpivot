-- ======================================================
-- V0160 down：撤销 `1901` / `6401` 两个补种科目
--
-- 两条安全阀（缺一条都会把审计链弄断）：
--   1. 只删**本迁移种进来的那两行**（按 id + 编码双条件），运维自己建的
--      `1901` / `6401`（不同 id）一行不动；
--   2. 只要 `biz_voucher_entry` 里有任何一个科目编码被引用过，就整条 no-op ——
--      否则分录的 `account_id` 会变成悬空引用（凭证是「只增不改」的审计台账，
--      宁可科目留着，也不能让历史凭证对不上科目）。
-- ======================================================

DELETE FROM biz_account
 WHERE account_code IN ('1901', '6401')
   AND id IN ('d1370004-0000-4000-8000-000000000901',
              'd1370004-0000-4000-8000-000000000902')
   AND NOT EXISTS (
        SELECT 1 FROM biz_voucher_entry e
         WHERE e.account_code IN ('1901', '6401')
   );

-- 自检：结束时「本迁移的两行」要么都在（有引用，保留），要么都不在（已回滚）；
-- 不允许出现只删掉一半。
DO $$
DECLARE
    n INT;
BEGIN
    SELECT count(*) INTO n
      FROM biz_account
     WHERE id IN ('d1370004-0000-4000-8000-000000000901',
                  'd1370004-0000-4000-8000-000000000902');
    IF n NOT IN (0, 2) THEN
        RAISE EXCEPTION 'V0160 down 自检失败：补种科目只删掉了一部分（剩 % 行）', n;
    END IF;
END $$;
