-- ======================================================
-- V0087 回滚：撤回公告用户侧读权限种子
--
-- 顺序：先删授权（sys_role_menu），再删按钮，最后删页面 —— 与外键/语义方向
-- 一致（页面被按钮 parent_id 引用，先删页面会留下孤立按钮）。
--
-- 口径说明：`sys_role_menu` 没有 `source` 列，迁移插入的行与运维手工授予的行不可区分，
-- 所以回滚口径是「回到 V0087 之前的状态」：本迁移种的这两个节点上的授权一律收回。
-- 运维若在 V0087 之后手工补授过，需要回滚后重新授一次 —— 这正是「回滚到迁移前」的定义。
-- ======================================================

DELETE FROM sys_role_menu
 WHERE menu_id IN ('20000000-0000-0000-0000-000000000700'::uuid,
                   '20000000-0000-0000-0000-000000000701'::uuid);

DELETE FROM sys_menu WHERE id = '20000000-0000-0000-0000-000000000701'::uuid;
DELETE FROM sys_menu WHERE id = '20000000-0000-0000-0000-000000000700'::uuid;
