-- V0144 回滚：删掉库存调拨的菜单 / 按钮与它们的角色授权。
--
-- 顺序：先删 `sys_role_menu`（无 ON DELETE CASCADE），再删 `sys_menu`。
-- 只删本迁移种的固定 UUID（0987–0992 共 6 个节点），不动运维后来手工加的其它菜单。
-- 权限码本身没有独立表（`sys_menu.auth_code` 即来源），删菜单即删码。
-- 不动任何业务表：本迁移只种权限。

DELETE FROM sys_role_menu
 WHERE menu_id IN (
        '20000000-0000-0000-0000-000000000987'::uuid,
        '20000000-0000-0000-0000-000000000988'::uuid,
        '20000000-0000-0000-0000-000000000989'::uuid,
        '20000000-0000-0000-0000-000000000990'::uuid,
        '20000000-0000-0000-0000-000000000991'::uuid,
        '20000000-0000-0000-0000-000000000992'::uuid
   );

DELETE FROM sys_menu
 WHERE id IN (
        '20000000-0000-0000-0000-000000000987'::uuid,
        '20000000-0000-0000-0000-000000000988'::uuid,
        '20000000-0000-0000-0000-000000000989'::uuid,
        '20000000-0000-0000-0000-000000000990'::uuid,
        '20000000-0000-0000-0000-000000000991'::uuid,
        '20000000-0000-0000-0000-000000000992'::uuid
   );

-- 零残留自检
DO $$
DECLARE
    n_left integer;
BEGIN
    SELECT count(*) INTO n_left
      FROM sys_menu
     WHERE auth_code LIKE 'business:erp:transfer:%';
    IF n_left <> 0 THEN
        RAISE EXCEPTION 'V0144 down 失败：还剩 % 个调拨权限菜单节点', n_left;
    END IF;
    SELECT count(*) INTO n_left
      FROM sys_role_menu
     WHERE menu_id IN (
            '20000000-0000-0000-0000-000000000987'::uuid,
            '20000000-0000-0000-0000-000000000988'::uuid,
            '20000000-0000-0000-0000-000000000989'::uuid,
            '20000000-0000-0000-0000-000000000990'::uuid,
            '20000000-0000-0000-0000-000000000991'::uuid,
            '20000000-0000-0000-0000-000000000992'::uuid
       );
    IF n_left <> 0 THEN
        RAISE EXCEPTION 'V0144 down 失败：还剩 % 条角色授权', n_left;
    END IF;
    RAISE NOTICE 'V0144 down 通过：调拨菜单 / 按钮 / 授权零残留';
END $$;
