-- ---------- 4) 自检（失败即迁移失败 → 启动失败） ----------
DO $$
DECLARE
    cat_cnt   int;
    doc_cnt   int;
    ver_cnt   int;
    thin_cnt  int;
    cross_cnt int;
BEGIN
    -- 4.1 两个新分类在、且启用
    SELECT count(*) INTO cat_cnt
      FROM sys_help_category
     WHERE id IN ('26000000-0000-4000-8000-000000000004'::uuid,
                  '26000000-0000-4000-8000-000000000005'::uuid)
       AND status = 1
       AND deleted_at IS NULL;
    IF cat_cnt <> 2 THEN
        RAISE EXCEPTION 'V0131 自检失败：新分类应为 2 个且启用，实际 %', cat_cnt;
    END IF;

    -- 4.2 5 篇文档在、已发布、有发布时间
    SELECT count(*) INTO doc_cnt
      FROM sys_help_doc
     WHERE id IN ('26500000-0000-4000-8000-000000000001'::uuid,
                  '26500000-0000-4000-8000-000000000002'::uuid,
                  '26500000-0000-4000-8000-000000000003'::uuid,
                  '26500000-0000-4000-8000-000000000004'::uuid,
                  '26500000-0000-4000-8000-000000000005'::uuid)
       AND status = 'PUBLISHED'
       AND published_at IS NOT NULL
       AND version = 1
       AND deleted_at IS NULL;
    IF doc_cnt <> 5 THEN
        RAISE EXCEPTION 'V0131 自检失败：示范文档应为 5 篇且 PUBLISHED，实际 %', doc_cnt;
    END IF;

    -- 4.3 每篇一条 version = 1 的快照
    SELECT count(*) INTO ver_cnt
      FROM sys_help_doc_version
     WHERE doc_id IN ('26500000-0000-4000-8000-000000000001'::uuid,
                      '26500000-0000-4000-8000-000000000002'::uuid,
                      '26500000-0000-4000-8000-000000000003'::uuid,
                      '26500000-0000-4000-8000-000000000004'::uuid,
                      '26500000-0000-4000-8000-000000000005'::uuid)
       AND version = 1;
    IF ver_cnt <> 5 THEN
        RAISE EXCEPTION 'V0131 自检失败：版本快照应为 5 条，实际 %', ver_cnt;
    END IF;

    -- 4.4 正文不能是占位符：每篇至少 800 字节（卡面要求 30–80 行可照做内容）
    SELECT count(*) INTO thin_cnt
      FROM sys_help_doc
     WHERE id IN ('26500000-0000-4000-8000-000000000001'::uuid,
                  '26500000-0000-4000-8000-000000000002'::uuid,
                  '26500000-0000-4000-8000-000000000003'::uuid,
                  '26500000-0000-4000-8000-000000000004'::uuid,
                  '26500000-0000-4000-8000-000000000005'::uuid)
       AND octet_length(content_md) < 800;
    IF thin_cnt > 0 THEN
        RAISE EXCEPTION 'V0131 自检失败：% 篇文档正文过短（< 800 字节）', thin_cnt;
    END IF;

    -- 4.5 分类归属正确：快速开始 2 篇、任务管理 2 篇、审批流 1 篇
    SELECT count(*) INTO cross_cnt
      FROM sys_help_doc
     WHERE (id = '26500000-0000-4000-8000-000000000001'::uuid
            AND category_id <> '26000000-0000-4000-8000-000000000001'::uuid)
        OR (id = '26500000-0000-4000-8000-000000000002'::uuid
            AND category_id <> '26000000-0000-4000-8000-000000000001'::uuid)
        OR (id = '26500000-0000-4000-8000-000000000003'::uuid
            AND category_id <> '26000000-0000-4000-8000-000000000004'::uuid)
        OR (id = '26500000-0000-4000-8000-000000000004'::uuid
            AND category_id <> '26000000-0000-4000-8000-000000000004'::uuid)
        OR (id = '26500000-0000-4000-8000-000000000005'::uuid
            AND category_id <> '26000000-0000-4000-8000-000000000005'::uuid);
    IF cross_cnt > 0 THEN
        RAISE EXCEPTION 'V0131 自检失败：% 篇文档挂错分类', cross_cnt;
    END IF;

    RAISE NOTICE 'V0131 自检通过：2 个分类 + 5 篇已发布文档 + 5 条版本快照';
END
$$;
