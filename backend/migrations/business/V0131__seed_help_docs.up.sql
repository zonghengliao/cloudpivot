## 一、5 个状态

| 状态码 | 中文 | 含义 | 是否终态 |
|---|---|---|---|
| `TODO` | 待开始 | 已建单，还没人动 | 否 |
| `DOING` | 进行中 | 有人在做 | 否 |
| `REVIEW` | 待验收 | 交付了，等验收人点头 | 否 |
| `DONE` | 已完成 | 验收通过 / 免验收直接完成 | 是 |
| `CANCELLED` | 已取消 | 不做了 | 是 |

## 二、10 条合法流转

状态机是一张**常量白名单**：25 种 `from → to` 组合里只放行下面 10 条，
表外组合一律返回 `400 / 63010`（状态流转不合法）。

| # | 流转 | 谁能推 | 进度副作用 |
|---|---|---|---|
| 1 | `TODO → DOING` | 负责人 / 分派人 / 创建人 / 管理员 | 抬到 ≥ 10% |
| 2 | `DOING → REVIEW` | 负责人 | 强制 100% |
| 3 | `DOING → DONE` | 负责人 / 创建人（**仅免验收任务**） | 强制 100%，写完成时间 |
| 4 | `REVIEW → DONE` | 创建人 / 分派人 / 管理员 | 强制 100%，写完成时间 |
| 5 | `REVIEW → DOING`（打回） | 创建人 / 分派人 / 管理员 | 回退到 10%，**必须填打回理由** |
| 6 | `DONE → DOING`（重开） | 创建人 / 管理员 | 回退到 10%，清完成时间 |
| 7 | `TODO → CANCELLED` | 负责人 / 创建人 / 分派人 / 管理员 | 不变 |
| 8 | `DOING → CANCELLED` | 同上 | 不变 |
| 9 | `REVIEW → CANCELLED` | 同上 | 不变 |
| 10 | `CANCELLED → TODO`（恢复） | 创建人 / 管理员 | 归零 |

### 两条容易踩的规则

1. **勾了「是否需验收」（`need_review = true`）的任务**：`DOING` 只能进 `REVIEW`，
   想直接「完成」会被拒（`63010`，理由「需验收任务必须先提交验收」）。
2. **没有验收权限的人点「验收通过」**：返回 `403 / 63011`。
   负责人自己不能验收自己交付的活。

## 三、进度的两种模式

### 模式 A：有子任务 → 自动汇总（父任务不可手改）

父任务一旦有子任务，进度由子任务算出，**直改父任务进度会返回 `409 / 63012`
（进度被锁定：请修改子任务进度）**。

汇总口径：

| 场景 | 算法 |
|---|---|
| 所有子任务都填了工时（> 0） | **工时加权**：`Σ(子任务工时 × 子任务进度) / Σ(子任务工时)` |
| 有任意子任务工时为空或 0 | **等权平均**：`Σ子任务进度 / 子任务数` |

> 为什么工时「不全」时不把空工时当 0 权重：那会把没填工时的子任务当成「不存在」，
> 一个 0% 的大活被沉默掉。等权是更保守的降级。

### 模式 B：没有子任务 → 手动填

无子任务的叶子任务直接改 `progress`（0–100）。状态流转仍会带副作用：
进入 `DOING` 抬到 ≥ 10%，进入 `REVIEW` / `DONE` 拉满 100%。

