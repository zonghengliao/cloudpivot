## 二、看板拖拽改状态

看板把 5 个状态画成 5 列。拖拽只允许走到**合法的下一列**：

```
待开始 ──▶ 进行中 ──▶ 待验收 ──▶ 已完成
   │           │           │
   └───────────┴───────────┴──▶ 已取消
```

- 从「待开始」不能直接拖到「已完成」（会被拒，错误码 `63010`：状态流转不合法）；
- 拖到「待验收」只有**负责人**能做；拖「待验收 → 已完成」只有**创建人 / 分派人 / 管理员**能做（错误码 `63011`：无权变更状态）；
- 免验收任务（未勾「是否需验收」）可以「进行中 → 已完成」一步到位。

