2. 从左侧节点栏**拖**一个「开始」到画布，再拖「审批」「结束」；
3. 按住节点右侧的圆点**拖出连线**到下一个节点（连线即流转方向）；
4. 点节点 → 右侧属性面板设「审批人」（用户 / 角色 / 发起人主管）；
5. 点「保存」（存草稿）→ 点「发布」生成新版本。

> 编辑器不画「回退线」：打回由审批人在待办里点「驳回」，引擎自动回到上一节点。

## 三、三个节点范例

### 范例 1：单签（最常用）

```
START → APPROVAL(直属主管) → END
```

适用：3 天以内的请假、500 元以内的报销。

### 范例 2：会签（财务多人）

```
START → APPROVAL(主管) → COUNTERSIGN(财务A + 财务B) → END
```

会签节点上只要有一个人驳回，整个节点即被打回；全部通过才继续往下走。

### 范例 3：条件分流

```
START → CONDITION(amount > 5000) ─ true  ─▶ APPROVAL(财务总监) → END
                                └ false ─▶ END
```

条件表达式在保存时校验；不支持的表达式形态返回 `65032`（表达式不支持）。

## 四、发布与版本

- 「发布」= 生成一个新版本并把旧版本降为 `ARCHIVED`：**任一时刻每个流程只有 1 个
  `PUBLISHED` 版本**；
- 已经在跑的审批实例钉的是**发起时**那个版本，后续改图不影响在途实例；
- 流程定义有 `graph_hash`，每日自检任务会核对「存库的图」与「哈希」是否一致。

## 五、发起一次审批

1. 审批流 → 我的待办 / 发起申请 → 选流程（如「报销审批」）→ 填表单 → 提交；
2. 引擎按图生成审批实例与逐节点的审批任务；
3. 审批人在「我的待办」里通过 / 驳回，全部通过后实例 = 已通过。

### 审批中的任务为什么拖不动

如果审批流程的业务类型是 `TASK_ACCEPT`，任务从 `REVIEW` 推到 `DONE` 会先过门闸：
任务挂了未完成的审批实例时，返回 **`409 / 65030`（审批中，暂不能变更状态）**；
审批通过后，引擎以回调身份自动把任务推到 `DONE`（或打回 `DOING`）。

