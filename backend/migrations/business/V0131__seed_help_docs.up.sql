-- ---------- 3) 每篇一条版本快照（version = 1） ----------
-- 用 `INSERT … SELECT … WHERE NOT EXISTS`：文档若因 slug 冲突被跳过，这里也不会插，
-- 不会撞 FK；重复执行也不会撞 `uk_sys_help_doc_version`。
