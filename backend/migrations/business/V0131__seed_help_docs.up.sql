## 一、拆子任务

1. 打开父任务详情 → 「子任务」区块 → 「新建子任务」；
2. 或在新建任务时把「父任务」指向已有任务。

规则：

| 规则 | 违反时的返回 |
|---|---|
| 最多 **2 层**（父 → 子；子任务不能再挂子任务） | `400 / 63005`（父任务不合法） |
| 父任务不能是自己 | `400 / 63005` |
| 父任务有未完成的子任务时不能被「完成」 | `409 / 63006`（存在未完成子任务） |

拆完以后父任务进度不再手填 —— 由子任务自动汇总（见《任务状态与进度规则》）。

## 二、FS 依赖（完成—开始）

当前只支持一种依赖类型 **FS（Finish-to-Start）**：前置任务做完了，后置任务才能开始。

- 入口：任务详情 → 「前置任务」→ 选择一个任务；
- 前置未完成时把后置任务拖到「进行中」→ `409 / 63102`（前置依赖未完成）；
- 依赖关系写进变更日志，可审计。

## 三、环检测

依赖图不允许出现环（A 等 B、B 等 C、C 又等 A）。加边时同步做深度优先检测：

| 情况 | 返回 |
|---|---|
| 自己依赖自己 / 不存在的任务 | `400 / 63103`（依赖不合法） |
| 加边后形成环（A→B→C→A） | `409 / 63101`（依赖成环） |
| 依赖关系已不存在（删的时候） | `404 / 63104`（依赖不存在） |

> 设计取舍：环检测在**写边时**做，不在读的时候做 —— 让脏图根本进不了库。

## 四、甘特图拖拽改期

甘特视图按 `start_date` / `due_date` 画条形，支持左右拖拽平移、拉两端改时长。

| 场景 | 行为 |
|---|---|
| 拖拽范围非法（结束早于开始） | `400 / 63105`（排期范围不合法） |
| 平移后早于前置任务完成日 | `409 / 63110`（不能早于前置任务） |
| 平移后晚于后置任务开始日 | `409 / 63111`（不能晚于后置任务） |
| 子任务超出父任务区间 | `409 / 63112`（超出父任务范围） |

甘特视图里的拖拽是**直接落库**的（不是草稿），所以每次拖完界面会刷新一次任务行。

