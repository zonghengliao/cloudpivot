-- ======================================================

DELETE FROM sys_role_menu
 WHERE menu_id IN (
     '20000000-0000-0000-0000-000000002895'::uuid,
     '20000000-0000-0000-0000-000000002896'::uuid,
     '20000000-0000-0000-0000-000000002897'::uuid,
     '20000000-0000-0000-0000-000000002898'::uuid
 );

DELETE FROM sys_menu
 WHERE id IN (
     '20000000-0000-0000-0000-000000002896'::uuid,
     '20000000-0000-0000-0000-000000002897'::uuid,
     '20000000-0000-0000-0000-000000002898'::uuid
 );

DELETE FROM sys_menu
 WHERE id = '20000000-0000-0000-0000-000000002895'::uuid;
