-- 12_history_adjust.sql —— 历史返利凭证「贷记佣金科目」的**人工调账**参考（不在任何迁移里跑）
--
-- 卡：t_627d2a4b（返利红字凭证贷记错科目）
-- 口径：**历史票不追溯**（见 `backend/app/migrations/business/V0445__sales_rebate_payable_account.up.sql`
--       文件头「口径取舍」）。本文件只是「万一真有生产历史错票要调」时的现成查数 + 调账口径，
--       **不要**把它塞进迁移，也**不要**在没有人工评审的情况下直接执行。
--
-- 什么时候需要它：
--   某个库在 V0445 之前就开过返利红字发票（贷记 2241.02 其他应付款-佣金），
--   且这些票是**真实业务**（不是夹具）。此时总账里「佣金应付」被返利负债污染，
--   佣金往来对账会多出不属于它的余额 —— 需要一张「借 2241.02 / 贷 2241.05」的同额调整凭证留痕。
--
-- 什么时候不需要它（本仓当前的实际状态）：
--   ① 生产 144：V0440 从未跑过（`biz_sales_rebate_*` 表不存在），2241.02 上 0 条分录
--      —— 见 `00_prod_precheck.txt`；
--   ② 99 / 145 的演练库、开发库：中招的凭证都是夹具造的测试数据，调账等于往练习环境里造假账。
--
-- ============================================================================
-- ① 先查：哪些历史返利凭证把负债记到了佣金科目上（一行 = 一张需要调整的票）
-- ============================================================================
SELECT s.settlement_no,
       s.invoice_no,
       v.voucher_no,
       v.voucher_date,
       e.account_code AS wrong_account,
       e.account_name AS wrong_account_name,
       e.credit_amount,
       s.settled_at
  FROM biz_sales_rebate_settlement s
  JOIN biz_voucher v ON v.id = s.voucher_id
  JOIN biz_voucher_entry e ON e.voucher_id = s.voucher_id
 WHERE s.voucher_id IS NOT NULL
   AND s.deleted_at IS NULL
   AND e.credit_amount > 0
   AND e.account_code LIKE '2241%'
   AND e.account_code <> '2241.05'
 ORDER BY s.settlement_no;

