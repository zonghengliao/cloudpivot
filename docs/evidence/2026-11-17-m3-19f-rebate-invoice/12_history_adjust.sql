-- 若真有行且是真业务，按下面的口径调账。

-- ============================================================================
-- ② 调账口径（**走业务路径，不走裸 SQL**）
--
--   分录：     借 2241.02 其他应付款-佣金      Σcredit_amount     （把错记的负债从佣金科目挪走）
--              贷 2241.05 其他应付款-销售返利  Σcredit_amount     （记到它该在的科目上）
--   摘要：     「调账：返利负债科目更正，原凭证 PZ-xxx / 结算单 RB-xxx（V0445 口径更正）」
--   期间：     必须落在**未结账**期间（`biz_accounting_period.status = 'OPEN'`）；
--              原票所属期间若已结账，就记在当期（会计上的「当期差错更正」）。
--
--   为什么不用 INSERT 直接写库：
--     `voucher::post_voucher` 是全部凭证写路径的唯一收口 —— 编号（biz_seq）、借贷平衡、
--     末级科目闸（`is_leaf = 1`）、期间未结账、辅助核算维度、头金额 = 分录取和，
--     全在它里面校验；绕过它直接 INSERT 会造出「头金额对不上 / 编号重号 / 记进已结账期间」
--     的坏凭证，而且没有任何审计痕迹。裸 SQL 只允许出现在**查数**里（①）。
--
--   实操：
--     1. 用有「手工凭证」权限的账号登录，新增一张手工凭证（POST `/business/erp/voucher`
--        → 审核 → 记账，对应 `voucher_write::create_manual_voucher` / `audit_voucher` /
--        `post_audited_voucher`）；
--     2. 两行分录按上面的科目与金额填，金额取自 ① 的 Σ（同一张结算单的贷方行合计）；
--     3. 一张历史票对应一张调整凭证，摘要里写原凭证号 + 结算单号，便于审计回溯；
--     4. 调完再跑一遍 ①，应当 0 行；`scripts/verify/erp_invariants.py --group 销售` 的
--        S11（返利红字凭证贷方口径）应从 WARN 转绿。
--
--   批量的情形：① 查出 N 张票时，可以合并成一张调整凭证（借贷各一行、金额为Σ），
--   但在摘要里列出全部结算单号；单张金额大 / 跨期的，按票逐张调更清楚。
-- ============================================================================
