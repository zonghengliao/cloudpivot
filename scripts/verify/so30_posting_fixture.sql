-- 三本账已扣 + 应收已挂」，走 API 造这条链要先把收货过账、发货过账、开票全跑一遍
-- （那是 SO-10 / SO-14 / SO-20 的 e2e 覆盖面）。本卡验的是**退货过账自身**的
-- 六件事，所以夹具直接落「过账后的正确形态」—— 但**成本单价、三本账数量金额、
-- 应收未收额都按真实口径摆**，否则断言就变成自证。
--
-- 三个客户 / 订单 / 发货单（互不干扰，各验一件事）：
--   A → SO30-SO-A / SH-A / OUT-A：**未开票**，验「部分退货 → 应收按额冲减」
--   B → SO30-SO-B / SH-B / OUT-B：**已开票**（IV-B ISSUED 1921），验「红字发票 + 收入冲减凭证」
--   C → SO30-SO-C / SH-C / OUT-C：**已收款 500**，验「退货金额 > 未收 → 409 且一笔不动」
--
-- 成本口径（物料种子 V0137）：
--   M-W1A-001（原料A）账面 100 件 / 金额 6000 → avg 60
--   M-W1B-002（原料B）账面  50 件 / 金额 6000 → avg 120
--   出库流水按上面单价记，退货过账要用它算回库成本（不是销售价）。
--
-- 幂等：开头按 SO30- 前缀 / 固定 UUID 清场，可反复执行。
-- =============================================================================
