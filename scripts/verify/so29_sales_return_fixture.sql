    SELECT id FROM biz_shipment WHERE ship_no LIKE 'SO29-SH-%');
DELETE FROM biz_shipment WHERE ship_no LIKE 'SO29-SH-%';
DELETE FROM biz_sales_order_item WHERE so_id IN (
    SELECT id FROM biz_sales_order WHERE so_no LIKE 'SO29-SO-%');
DELETE FROM biz_sales_order WHERE so_no LIKE 'SO29-SO-%';
