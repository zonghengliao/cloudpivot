-- =============================================================================
-- SO-29 验收夹具：一张「已过账」的发货单 + 一张未过账发货单（用于退货闸门）
-- =============================================================================
-- 为什么直写 SQL：退货的前置条件是「货已发出去（发货单 POSTED + 订单 delivered_qty
-- 已累加）」。走 API 造这条链要先把库存过账三本账（收货→入库→发货过账），那属于
-- SO-10/SO-24 的 e2e 覆盖面；本卡验的是**退货自身的 CRUD + 状态机 + 超退守卫**，
-- 所以夹具直接落「过账后的正确形态」（与 scripts/verify/so23_sales_fixture.sql 同口径）。
--
-- 三条订单行：
--   行 1：10 @100（13%）—— 已由 SO29-SH-0001 全部发出（可退 10）
--   行 2： 5 @200（13%）—— 已由 SO29-SH-0002 全部发出（可退 5）
--   行 3： 3 @50 （13%）—— 已出库但**没有发货单**（验「按订单退货」的 delivered_qty 口径）
--
-- 幂等：开头按 SO29- 前缀 / 固定 UUID 清场，可反复执行。
-- =============================================================================
\set ON_ERROR_STOP on

