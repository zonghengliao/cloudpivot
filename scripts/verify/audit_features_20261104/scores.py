rows = []
n_scores = 0
n_low = 0
for k,(name,sc) in S.items():
    assert len(sc)==8, k
    n_scores += len(sc)
    n_low += sum(1 for x in sc if x<=3)
    rows.append((sum(sc), k, name, sc))
rows.sort(reverse=True)
print("功能数:", len(rows), " 分数格数:", n_scores, " <=3 的格数:", n_low)
for t,k,n,sc in rows:
    band = "优秀" if t>=34 else ("良好" if t>=26 else ("及格" if t>=18 else "不合格"))
    print(f"{k:>2} {n:<14} {t:>2}/40  {band}  {sc}")
print("\n前5:")
for t,k,n,sc in rows[:5]: print(f"  {n} {t}")
print("后5:")
for t,k,n,sc in rows[-5:]: print(f"  {n} {t}")
print("\n平均分:", round(sum(r[0] for r in rows)/len(rows),2))
