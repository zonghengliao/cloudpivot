/**
 * 错误码 → 人话（**审批类** · P3-01）。
 *
 * # 为什么要有这个文件
 *
 * 用户拿到 `409 / 65023` 这种码只会懵：码说的是「引擎的哪条规则拒了」，用户要的是
 * 「我现在该点哪里」。本文件把 `backend/crates/cloudpivot-kernel/src/shared/error_code.rs`
 * 里 **65xxx 审批流整段**（`65001`–`65048`）+ 框架 HTTP 语义码（`400`/`403`/`409`…）翻成
 * 「现象 + 该怎么办」，由 `api/request.ts` 的响应拦截器统一查表 —— 一处收口，175 处
 * `showError(err.message)` 一个都不用改。
 *
 * # 取文口径（重要，别照卡面硬编）
 *
 * 卡面写「查表优先，查不到才用后端原文」。**实测不能这么做**：后端 65xxx 的 `msg` 几乎
 * 都是 `format!` 出来的**这一单的具体信息**，丢掉就是信息退化 ——
 *
 * | 码 | 后端实际 `msg`（`engine.rs` / `handler.rs`） |
 * |---|---|
 * | `65023` | `已有人审批（1 票），不能撤回；请联系流程管理员终止` |
 * | `65020` | `节点「销售主管审批」第 2 轮已经处理过（APPROVED），不能重复完成` |
 * | `65018` | `节点「财务审批」没有可用审批人（候选 0 人，角色 财务主管）` |
 *
 * 表里的通用文案给不出「1 票 / 哪个节点」。所以与 `views/business/flow/components/
 * flow-error-codes.ts::taskNodeErrorText` 的既有口径保持一致：**后端原文优先，表兜底**，
 * 但加一条判据 —— 后端文案里已经写了「该怎么办」（{@link GUIDANCE} 命中）才算自足；
 * 没写（`这条待办已处理，不能再加签` / `操作失败`）就把表里的动作指引补上去。
 *
 * 最终优先级：
 *
 * 1. **码在表里 + 后端文案自足** → 后端文案（最准，带这一单细节）
 * 2. **码在表里 + 后端文案不自足 / 没有** → 表里的「现象 + 怎么办」；后端原文若有，作为
 *    `（后端说明：…）` 附在后面（永不丢信息）
 * 3. **码不在表里 + 有后端文案** → 后端文案（`66xxx` ERP / `68xxx` HR 等归 P3-02 等后续卡）
 * 4. **什么都没有** → 按 HTTP 状态给通用人话；连状态都没有（网络层失败）给网络提示
 *
 * **任何一条分支都不会返回裸码**（`65023` / `409` 这种）—— 这正是本卡要消灭的形态。
 *
 * # 与 `flow-error-codes.ts` 的分工（别把两份文案搞混）
 *
 * - 流程**编辑器内联提示**（条件树 / 审批人表达式 / 任务节点配置）：走
 *   `views/business/flow/components/flow-error-codes.ts`，那份带发布校验规则号（R10 / R18），
 *   逐字对齐后端模板；
 * - **全局 toast 兜底**（任何请求失败的出参）：走本文件。
 * 层间隔：`constants/` 不 import `views/`，所以本文件对 `65016`/`65034`–`65039`
 * 写的是**通用**动作（「回到流程编辑器按提示改」），不复制那 30+ 条模板。
 *
 * # 加新码（P3-02 起照这个来）
 *
 * 1. 码值从 `error_code.rs` **抄过来**（`pub const X: i32 = 65xxx`），不许自造；
 * 2. 文案写「现象 + 该怎么办」，别写「错误码 xxx」这种码味的话；
 * 3. `tests/unit/error-messages.test.ts` 会**直接读 `error_code.rs`**：`65xxx` 段每新增
 *    一个常量而这里没登记，单测先红（与 `flow-error-codes.ts` 同一套做法）。
 */

