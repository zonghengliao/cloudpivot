/** 文案来源（排障 / 单测用）：`backend` 后端原文、`table` 业务码表、`http` HTTP 码表、`network` 网络层、`fallback` 最终兜底。 */
export type ErrorMessageSource = 'backend' | 'table' | 'http' | 'network' | 'fallback';

/** {@link resolveErrorMessage} 的入参（对齐 `ApiError` 的三个字段 + 后端原始 `msg`）。 */
export interface ErrorMessageInput {
  /** 业务状态码（`ApiError.code`；网络层失败为 `-1`） */
  code?: number | null;
  /** HTTP 状态码（拿不到响应时为 `undefined`） */
  status?: number | null;
  /** 后端 `msg` 原文 */
  message?: string | null;
}

/** {@link resolveErrorMessage} 的返回值：`message` 直接交给 `ApiError` / toast。 */
export interface ResolvedErrorMessage {
  /** 给用户看的一句话（**保证不是裸码**） */
  message: string;
  /** 这句话从哪来（排障与单测断言用，不影响展示） */
  source: ErrorMessageSource;
}

/** 纯码 / 纯数字 / 空白：都不算「后端给了人话」。 */
const BARE_CODE = /^[\s\d\-_.:/]+$/;

/** 是否含汉字（后端 `msg` 可能是 `Network Error` / `Internal Server Error` 这种）。 */
const HAS_CHINESE = /[\u4e00-\u9fa5]/;

/** 后端原文是否可用：非空、不是裸码、且有中文。 */
function usableBackendMessage(raw: string, code: number | null, status: number | null): string {
  if (!raw) return '';
  if (code !== null && raw === String(code)) return '';
  if (status !== null && raw === String(status)) return '';
  if (BARE_CODE.test(raw)) return '';
  if (!HAS_CHINESE.test(raw)) return '';
  return raw;
}

/**
 * 码 / 状态 / 后端原文 → 一句人话（见文件头「取文口径」的四条优先级）。
 *
 * ```ts
 * resolveErrorMessage({ code: 65023, status: 409 }).message;
 * // → '这张审批单已经有人审批过了，不能撤回。如需终止，请让流程管理员在审批单详情里终止流程'
 * ```
 */
export function resolveErrorMessage(input: ErrorMessageInput = {}): ResolvedErrorMessage {
  const code = typeof input.code === 'number' ? input.code : null;
  const status = typeof input.status === 'number' ? input.status : null;
  const backend = usableBackendMessage((input.message ?? '').trim(), code, status);
  const byCode = code === null ? undefined : ERROR_MESSAGES[String(code)];
  // 业务码（`10000` 起）/ 框架语义码（`400`–`599`）分开标来源：前者是我们翻的人话，后者是 HTTP 通用话
  const tableSource: ErrorMessageSource = code !== null && code >= 10000 ? 'table' : 'http';

  if (byCode) {
    // 后端已经说了「该怎么办」→ 它比表更准（带这一单的票数 / 节点名 / 环路径）
    if (backend && GUIDANCE.test(backend)) {
      return { message: backend, source: 'backend' };
    }
    return {
      message: backend ? `${byCode}（后端说明：${backend}）` : byCode,
      source: tableSource,
    };
  }
  // 表里没有（`67xxx` PDF / `68xxx` HR 等归后续卡）：后端说了什么就显示什么，别拿通用话盖掉具体信息
  if (backend) {
    return { message: backend, source: 'backend' };
  }
  if (status !== null) {
    const byStatus = ERROR_MESSAGES[String(status)];
    if (byStatus) {
      return { message: byStatus, source: 'http' };
    }
  }
  // 连 HTTP 状态都没有 = 没拿到响应（断网 / 跨域 / 超时）
  if (status === null) {
    return { message: NETWORK_MESSAGE, source: 'network' };
  }
  return { message: FALLBACK_MESSAGE, source: 'fallback' };
}
